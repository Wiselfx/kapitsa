#!/usr/bin/env python3
"""Write a header naming every matvec kernel the Metal sources actually define.

Spark::matvec_pipe picks a kernel name from the weight format, K, N and how the result is consumed. If the name it
builds is not instantiated, the failure is a fatal "no such pipeline" on a Mac at run time -- which is how two defects
in this port were found -- so tools/spark_config_test.cpp sweeps that rule against the real kernel set.

The first version of that test hand-typed the set and got it wrong twice over: it used "f16g64" for bf16 (wfmt.metal's
suffix is "_f16", and SparkLinear::fmt returns "f16"), so the format a bf16 checkpoint uses was never checked at all,
and it claimed qmvg_f8g64 decode kernels that are never instantiated (decode is the NI_WF_NO8 group; 8-bit takes its
own qmv2_b8/qmv3_b8 path). A list restated from memory cannot catch a disagreement with the sources, so it is parsed
from them here and the test compares against this.

  tools/spark_kernel_names.py <src/kernels> <out.h>
"""
import pathlib
import re
import sys

QMV_DECL = re.compile(r"NI_QMV[23]\(\s*([A-Za-z0-9_]+)\s*,")


def macro_body(text: str, name: str) -> str:
    """The text of a #define, from after its parameter list to the end of the line (continuations joined)."""
    m = re.search(rf"^#define\s+{name}\b(.*?)(?=^#define|^[^\s\\]|\Z)", text, re.S | re.M)
    return m.group(1) if m else ""


def bound_formats(wfmt: str, group: str) -> list:
    """The (format, bits, group) triples a format group binds, e.g. NI_WF_NO8 -> f16, f6g64, ..."""
    expanded = macro_body(wfmt, group)
    for ref in re.findall(r"(NI_WF_[A-Z0-9]+)\(X\)", expanded):
        expanded += macro_body(wfmt, ref)
    seen = []
    for f in re.findall(r"X\(\s*([a-z0-9]+)\s*,", expanded):
        if f not in seen:
            seen.append(f)
    return seen


def main() -> int:
    src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "src/kernels")
    out = pathlib.Path(sys.argv[2] if len(sys.argv) > 2 else "/dev/stdout")
    qmv = (src / "qmv.metal").read_text()
    wfmt = (src / "wfmt.metal").read_text()

    names = set(QMV_DECL.findall(qmv))
    names.discard("NAME")  # the macro's own parameter list

    # wfmt's flexible-format kernels: NI_WF_DECODE(SFX, F, GS) emits NI_QMVG(qmvg_##SFX##_<rows>, ...) for each format
    # in the group it is applied to, which is NI_WF_NO8.
    decode = macro_body(wfmt, "NI_WF_DECODE")
    rows = re.findall(r"NI_QMVG\(qmvg_##SFX##_([A-Za-z0-9_]+)", decode)
    for fmt in bound_formats(wfmt, "NI_WF_NO8"):
        for r in rows:
            names.add(f"qmvg_{fmt}_{r}")

    names.discard("")
    body = "".join(f'    "{n}\\n"\n' for n in sorted(names))
    out.write_text(
        "// generated by tools/spark_kernel_names.py from src/kernels/{qmv,wfmt}.metal -- do not edit\n"
        "// Every matvec kernel the kernel sources instantiate, for spark_config_test's sweep of matvec_pipe.\n"
        "namespace ni { inline constexpr const char* kSparkMatvecNames =\n" + body + "    ; }\n"
    )
    print(f"spark_kernel_names: {len(names)} matvec kernels -> {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
